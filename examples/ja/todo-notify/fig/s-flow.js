// 1件の期限が通知になるまで。コマごとに1段ずつ現れる
const S = [
  ['期限を付ける', ['初めてなら', '許可を聞く'], 'Q03'],
  ['1時間前を出す', ['鳴らす時刻＝', '期限 − 1時間'], 'Q02'],
  ['静かな時間か', ['22時〜7時なら', '21:30 に前倒し'], 'Q06'],
  ['今日の数を見る', ['3件目までは1件で', '4件目からまとめへ'], 'Q04'],
  ['通知を出す', ['「完了」', '「1時間後」付き'], 'Q05']
];
let s = defs('sf');
S.forEach(([h, items, id], i) => {
  const x = 20 + i * 196, last = i === 4;
  s += '<g data-step="' + (i + 1) + '">'
    + '<rect x="' + x + '" y="30" width="176" height="150" rx="4" style="fill:var(--' + (last ? 'accent-soft' : 'surface') + ');stroke:var(--' + (last ? 'accent' : 'frame') + ');stroke-width:' + (last ? 1.5 : 1) + '"/>'
    + MONO(x + 12, 52, String(i + 1), 'mute', 12) + T(x + 30, 52, h, 'ink', 13, 700)
    + TL(x + 12, 88, items, 'ink', 12)
    + MONO(x + 12, 164, id, 'mute', 12)
    + (i < 4 ? flow('M' + (x + 177) + ' 105 H' + (x + 194), 'ink', 'sf') : '')
    + '</g>';
});
return '<svg viewBox="0 0 1000 200" role="img" aria-label="1件の期限が通知になるまでの5段。1 期限を付ける。初めてなら許可を聞く。2 鳴らす時刻を期限の1時間前にする。3 22時から7時なら21時30分に前倒し。4 今日3件目までは1件ずつ、4件目からまとめへ。5 完了と1時間後のボタン付きで通知を出す。">' + s + '</svg>';
